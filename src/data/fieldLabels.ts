export function getFieldLabel(path: string, fallback?: string): string {
    const lastSegment = path.split(".").pop() ?? path;
    const key = normalizeFieldKey(lastSegment);

    return fieldLabels[key] ?? fallback ?? lastSegment.replaceAll("_", " ");
}